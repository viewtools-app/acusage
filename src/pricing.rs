/// Which layer gave a model its price (`Local` is a local model counted at $0).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum PriceSource {
    Config,
    Builtin,
    Litellm,
    Local,
}

#[derive(Debug, Clone)]
pub struct PriceTable {
    /// Layers, highest priority first: config `[prices]`, official `BUILTIN`, LiteLLM snapshot.
    layers: [HashMap<String, Price>; 3],
}

/// LiteLLM snapshot generated by `scripts/` (USD per million, already converted).
const LITELLM_JSON: &str = include_str!("../data/litellm-prices.json");

#[derive(Deserialize)]
struct LitellmFile {
    models: HashMap<String, [f64; 5]>,
}

/// Strip a trailing `-YYYYMMDD` suffix, if present.
fn strip_date(id: &str) -> Option<&str> {
    let (head, tail) = id.rsplit_once('-')?;
    (tail.len() == 8 && tail.bytes().all(|b| b.is_ascii_digit())).then_some(head)
}

/// Strip a trailing Gemini thinking-level suffix, if present.
fn strip_thinking(id: &str) -> Option<&str> {
    let (head, tail) = id.rsplit_once('-')?;
    matches!(tail, "high" | "medium" | "low" | "minimal").then_some(head)
}

/// Strip a trailing `-thinking` or `-tiered` variant suffix, if present.
fn strip_variant(id: &str) -> Option<&str> {
    let (head, tail) = id.rsplit_once('-')?;
    matches!(tail, "thinking" | "tiered").then_some(head)
}

/// A local (Ollama-style) model id: exactly one `:`, not an `ft:` fine-tune or `arn:` id, and a
/// non-empty tag after the `:` that is not all digits. Bedrock ids (`-v1:0`, `-v1:0:48k`) never match.
pub fn is_local_id(id: &str) -> bool {
    if id.starts_with("ft:") || id.starts_with("arn:") {
        return false;
    }
    let mut parts = id.split(':');
    matches!(
        (parts.next(), parts.next(), parts.next()),
        (Some(_), Some(tag), None) if !tag.is_empty() && !tag.bytes().all(|b| b.is_ascii_digit())
    )
}

impl PriceTable {
    /// Official table over the embedded LiteLLM snapshot (parsed once per call; built once per run).
    pub fn builtin() -> Self {
        Self::with_litellm_json(LITELLM_JSON).expect("embedded data/litellm-prices.json is valid")
    }

    /// Official table over a LiteLLM layer parsed from `json`.
    pub fn with_litellm_json(json: &str) -> Result<Self, serde_json::Error> {
        let file: LitellmFile = serde_json::from_str(json)?;
        let litellm = file
            .models
            .into_iter()
            .map(|(id, [input, output, w5, w1, read])| {
                let p = Price {
                    input,
                    output,
                    cache_write_5m: w5,
                    cache_write_1h: w1,
                    cache_read: read,
                };
                (id, p)
            })
            .collect();
        let official = BUILTIN
            .iter()
            .map(|&(id, input, output, w5, w1, read)| {
                let p = Price {
                    input,
                    output,
                    cache_write_5m: w5,
                    cache_write_1h: w1,
                    cache_read: read,
                };
                (id.to_string(), p)
            })
            .collect();
        Ok(Self {
            layers: [HashMap::new(), official, litellm],
        })
    }

    /// Replace or add entries (config `[prices."model-id"]`), the top layer.
    pub fn with_overrides(mut self, overrides: HashMap<String, Price>) -> Self {
        self.layers[0].extend(overrides);
        self
    }

    /// Walk the layers in priority order; within a layer try the exact id, then the id with
    /// trailing `-YYYYMMDD` stripped, then a Gemini thinking level (`-high`, `-medium`, `-low`,
    /// `-minimal`), then a variant (`-thinking`, `-tiered`), then a level plus a variant
    /// (`-thinking-high`). A hit in a higher layer wins.
    pub fn lookup(&self, model: &str) -> Option<&Price> {
        self.lookup_layer(model).map(|(_, p)| p)
    }

    /// Like `lookup`, with the layer that matched; a local model gives `Local`, no price `None`.
    pub fn source(&self, model: &str) -> Option<PriceSource> {
        match self.lookup_layer(model) {
            Some((i, _)) => Some(
                [
                    PriceSource::Config,
                    PriceSource::Builtin,
                    PriceSource::Litellm,
                ][i],
            ),
            None => is_local_id(model).then_some(PriceSource::Local),
        }
    }

    /// Priced models of `records` (including local ones) mapped to their source.
    pub fn price_sources<'a>(
        &self,
        records: impl IntoIterator<Item = &'a UsageRecord>,
    ) -> BTreeMap<String, PriceSource> {
        records
            .into_iter()
            .filter_map(|r| Some((r.model.clone(), self.source(&r.model)?)))
            .collect()
    }

    fn lookup_layer(&self, model: &str) -> Option<(usize, &Price)> {
        self.layers.iter().enumerate().find_map(|(i, l)| {
            l.get(model)
                .or_else(|| strip_date(model).and_then(|m| l.get(m)))
                .or_else(|| strip_thinking(model).and_then(|m| l.get(m)))
                .or_else(|| strip_variant(model).and_then(|m| l.get(m)))
                .or_else(|| {
                    // A level after a variant, e.g. `-thinking-high`.
                    let m = strip_variant(strip_thinking(model)?)?;
                    l.get(m)
                })
                .map(|p| (i, p))
        })
    }

    /// True when the model has no price and its id looks like a local model (free at an API).
    pub fn is_local(&self, model: &str) -> bool {
        is_local_id(model) && self.lookup(model).is_none()
    }

    /// Cost in USD, or `None` when the model has no price. Local models cost 0.
    pub fn cost(&self, r: &UsageRecord) -> Option<f64> {
        let Some(p) = self.lookup(&r.model) else {
            return self.is_local(&r.model).then_some(0.0);
        };
        let tokens = [
            (r.input, p.input),
            (r.output, p.output),
            (r.cache_write_5m, p.cache_write_5m),
            (r.cache_write_1h, p.cache_write_1h),
            (r.cache_read, p.cache_read),
        ];
        Some(
            tokens
                .iter()
                .map(|&(n, per_m)| n as f64 * per_m)
                .sum::<f64>()
                / 1e6,
        )
    }

    /// Sorted, deduplicated models of `records` that have no price.
    pub fn unpriced<'a>(&self, records: impl IntoIterator<Item = &'a UsageRecord>) -> Vec<String> {
        let set: BTreeSet<&str> = records
            .into_iter()
            .filter(|r| self.lookup(&r.model).is_none() && !is_local_id(&r.model))
            .map(|r| r.model.as_str())
            .collect();
        set.into_iter().map(String::from).collect()
    }

    /// Sorted, deduplicated local models of `records` (counted at $0).
    pub fn local_models<'a>(
        &self,
        records: impl IntoIterator<Item = &'a UsageRecord>,
    ) -> Vec<String> {
        let set: BTreeSet<&str> = records
            .into_iter()
            .filter(|r| self.is_local(&r.model))
            .map(|r| r.model.as_str())
            .collect();
        set.into_iter().map(String::from).collect()
    }
}

