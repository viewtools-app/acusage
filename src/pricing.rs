    #[test]
    fn source_per_layer_with_fallbacks() {
        let t = PriceTable::with_litellm_json(FAKE_LITELLM).unwrap();
        assert_eq!(t.source("only-in-litellm"), Some(PriceSource::Litellm));
        assert_eq!(
            t.source("only-in-litellm-20260101"),
            Some(PriceSource::Litellm)
        );
        assert_eq!(t.source("claude-sonnet-5-5"), Some(PriceSource::Builtin));
        // a suffix fallback keeps the layer that matched
        assert_eq!(
            t.source("claude-sonnet-5-5-20261001"),
            Some(PriceSource::Builtin)
        );
        assert_eq!(t.source("not-anywhere"), None);
        let o = HashMap::from([("only-in-litellm".to_string(), custom())]);
        let t = t.with_overrides(o);
        assert_eq!(t.source("only-in-litellm"), Some(PriceSource::Config));
        assert_eq!(
            t.source("only-in-litellm-20260101"),
            Some(PriceSource::Config)
        );
        assert_eq!(t.source("claude-sonnet-5-5"), Some(PriceSource::Builtin));
        // thinking level, variant and level-after-variant fallbacks keep the matching layer
        let t = PriceTable::with_litellm_json(FAKE_LITELLM).unwrap();
        for id in [
            "only-in-litellm-high",
            "only-in-litellm-thinking",
            "only-in-litellm-thinking-high",
        ] {
            assert_eq!(t.source(id), Some(PriceSource::Litellm), "{id}");
        }
        for id in ["claude-opus-4-6-high", "claude-opus-4-6-thinking-high"] {
            assert_eq!(t.source(id), Some(PriceSource::Builtin), "{id}");
        }
        let o = HashMap::from([("only-in-litellm".to_string(), custom())]);
        let t = t.with_overrides(o);
        assert_eq!(
            t.source("only-in-litellm-thinking-high"),
            Some(PriceSource::Config)
        );
        // config overrides a built-in id
        let o = HashMap::from([("claude-sonnet-5-5".to_string(), custom())]);
        let t = PriceTable::with_litellm_json(FAKE_LITELLM)
            .unwrap()
            .with_overrides(o);
        assert_eq!(t.source("claude-sonnet-5-5"), Some(PriceSource::Config));
    }

