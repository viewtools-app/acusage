//! Price layers (config, official table, embedded LiteLLM snapshot), model matching and cost
//! calculation.
//! A model without a known price has no cost (`None`); a price is never guessed.

use crate::model::UsageRecord;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet, HashMap};

/// USD per million tokens.
#[derive(Debug, Clone, Copy, PartialEq, Deserialize)]
pub struct Price {
    pub input: f64,
    pub output: f64,
    pub cache_write_5m: f64,
    pub cache_write_1h: f64,
    pub cache_read: f64,
}

